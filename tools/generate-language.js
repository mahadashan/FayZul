#!/usr/bin/env node
// =============================================================================
// generate-language.js
//
// Reads language/language-definition.json (the single FayZul vocabulary)
// and writes:
//   src/keywords.h
//   src/operators.h
//   vscode-extension/syntaxes/fayzul.tmLanguage.json
//
// Run from the project root:
//   node tools/generate-language.js
// =============================================================================

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const DEF_PATH = path.join(ROOT, "language", "language-definition.json");

function loadDefinition() {
    const raw = fs.readFileSync(DEF_PATH, "utf8");
    return JSON.parse(raw);
}

function padMacro(name) {
    return name.padEnd(19, " ");
}

function generateKeywordsH(def) {
    let out = "";
    out += "// =============================================================================\n";
    out += "// keywords.h\n";
    out += "// AUTO-GENERATED from language/language-definition.json\n";
    out += "// Do not edit this file by hand. Run:  node tools/generate-language.js\n";
    out += "// =============================================================================\n";
    out += "\n";
    out += "#pragma once\n";
    out += "\n";

    let lastGroup = null;
    for (const kw of def.keywords) {
        if (kw.group !== lastGroup) {
            lastGroup = kw.group;
            out += "// ---------------------------------------------------------------------------\n";
            out += `// ${kw.groupTitle}\n`;
            out += "// ---------------------------------------------------------------------------\n";
        }
        const comment = kw.meaning ? `   // ${kw.meaning}` : "";
        out += `#define ${padMacro(kw.macro)} "${kw.word}"${comment}\n`;
        const next = def.keywords[def.keywords.indexOf(kw) + 1];
        if (!next || next.group !== kw.group) {
            out += "\n";
        }
    }

    return out;
}

function generateOperatorsH(def) {
    let out = "";
    out += "// =============================================================================\n";
    out += "// operators.h\n";
    out += "// AUTO-GENERATED from language/language-definition.json\n";
    out += "// Do not edit this file by hand. Run:  node tools/generate-language.js\n";
    out += "// =============================================================================\n";
    out += "\n";
    out += "#pragma once\n";
    out += "\n";
    out += "// ---------------------------------------------------------------------------\n";
    out += "// Comparison operators (word-based, not symbols)\n";
    out += "// ---------------------------------------------------------------------------\n";
    for (const op of def.comparisonOperators) {
        const comment = op.cpp ? `   // ${op.cpp}  (${op.meaning})` : "";
        out += `#define ${padMacro(op.macro)} "${op.word}"${comment}\n`;
    }
    out += "\n";
    out += "// ---------------------------------------------------------------------------\n";
    out += "// Logical operators (word-based)\n";
    out += "// ---------------------------------------------------------------------------\n";
    for (const op of def.logicalOperators) {
        const comment = op.cpp ? `   // ${op.cpp}  (${op.meaning})` : "";
        out += `#define ${padMacro(op.macro)} "${op.word}"${comment}\n`;
    }
    return out;
}

function alt(words) {
    const unique = [...new Set(words.filter(Boolean))];
    unique.sort((a, b) => b.length - a.length);
    return unique.map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|");
}

function generateTmLanguage(def) {
    const keywords = def.keywords;
    const controlWords = keywords
        .filter((k) => k.tmScope && k.tmScope.startsWith("keyword.control"))
        .map((k) => k.word);
    const otherWords = keywords
        .filter((k) => k.tmScope && k.tmScope.startsWith("keyword.other"))
        .map((k) => k.word);
    const boolWords = keywords
        .filter((k) => k.tmScope && k.tmScope.includes("boolean"))
        .map((k) => k.word);
    const nullWords = keywords
        .filter((k) => k.tmScope && k.tmScope.includes("null"))
        .map((k) => k.word);
    const cmpWords = def.comparisonOperators.map((o) => o.word);
    const logWords = def.logicalOperators.map((o) => o.word);
    const arithClass = def.arithmeticOperators
        .map((o) => o.symbol)
        .join("")
        .replace(/\\/g, "\\\\")
        .replace(/]/g, "\\]")
        .replace(/-/g, "\\-")
        .replace(/\^/g, "\\^");

    const grammar = {
        $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
        name: def.language.name,
        scopeName: "source.fayzul",
        patterns: [
            { include: "#comments" },
            { include: "#strings" },
            { include: "#numbers" },
            { include: "#booleans" },
            { include: "#null" },
            { include: "#keywords" },
            { include: "#comparisonOperators" },
            { include: "#logicalOperators" },
            { include: "#arithmeticOperators" }
        ],
        repository: {
            comments: {
                patterns: [
                    {
                        name: "comment.line.double-slash.fayzul",
                        match: "//.*$"
                    }
                ]
            },
            strings: {
                name: "string.quoted.double.fayzul",
                begin: "\"",
                end: "\"",
                patterns: [
                    {
                        name: "constant.character.escape.fayzul",
                        match: "\\\\."
                    }
                ]
            },
            numbers: {
                name: "constant.numeric.fayzul",
                match: "\\b\\d+(?:\\.\\d+)?\\b"
            },
            booleans: {
                name: "constant.language.boolean.fayzul",
                match: `\\b(?:${alt(boolWords)})\\b`
            },
            null: {
                name: "constant.language.null.fayzul",
                match: `\\b(?:${alt(nullWords)})\\b`
            },
            keywords: {
                patterns: [
                    {
                        name: "keyword.control.fayzul",
                        match: `\\b(?:${alt(controlWords)})\\b`
                    },
                    {
                        name: "keyword.other.fayzul",
                        match: `\\b(?:${alt(otherWords)})\\b`
                    }
                ]
            },
            comparisonOperators: {
                name: "keyword.operator.comparison.fayzul",
                match: `\\b(?:${alt(cmpWords)})\\b`
            },
            logicalOperators: {
                name: "keyword.operator.logical.fayzul",
                match: `\\b(?:${alt(logWords)})\\b`
            },
            arithmeticOperators: {
                name: "keyword.operator.arithmetic.fayzul",
                match: `[${arithClass}]`
            }
        }
    };

    grammar._comment = "AUTO-GENERATED from language/language-definition.json — do not edit by hand";
    return JSON.stringify(grammar, null, 4) + "\n";
}

function main() {
    const def = loadDefinition();

    const keywordsPath = path.join(ROOT, "src", "keywords.h");
    const operatorsPath = path.join(ROOT, "src", "operators.h");
    const tmPath = path.join(ROOT, "vscode-extension", "syntaxes", "fayzul.tmLanguage.json");

    fs.mkdirSync(path.dirname(tmPath), { recursive: true });

    fs.writeFileSync(keywordsPath, generateKeywordsH(def), "utf8");
    fs.writeFileSync(operatorsPath, generateOperatorsH(def), "utf8");
    fs.writeFileSync(tmPath, generateTmLanguage(def), "utf8");

    console.log("Generated:");
    console.log("  " + path.relative(ROOT, keywordsPath));
    console.log("  " + path.relative(ROOT, operatorsPath));
    console.log("  " + path.relative(ROOT, tmPath));
}

main();
